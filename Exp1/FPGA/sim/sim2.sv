`timescale 1ns / 1ps

module tb_UART_RX;

    // ============================================================
    // Señales
    // ============================================================

    logic clk;
    logic RX;
    logic reset;

    logic [7:0] data;
    logic ready;
    logic active;

    logic clk_UART;


    // ============================================================
    // M1: UART_RX
    // ============================================================

    UART_RX M1 (
        .clk      (clk),
        .clk_UART (clk_UART),
        .RX       (RX),
        .reset    (reset),
        .data     (data),
        .ready    (ready),
        .active   (active)
    );


    // ============================================================
    // M2: Clock divider
    // ============================================================

    clk_div #(
        .LIMIT       (52),
        .RESET_STATE (1'b0)
    ) M2 (
        .in_clk  (clk),
        .reset   (!active),
        .out_clk (clk_UART)
    );


    // ============================================================
    // Clock de 1 MHz
    //
    // Periodo = 1 us
    // Medio periodo = 500 ns
    // ============================================================

    initial begin
        clk = 1'b0;

        forever begin
            #500 clk = ~clk;
        end
    end


    // ============================================================
    // Estímulos
    // ============================================================

    initial begin

        // Estado inicial
        RX    = 1'b1;
        reset = 1'b1;

        // Reset durante 10 us
        #10_000;

        reset = 1'b0;

        // --------------------------------------------------------
        // RX permanece HIGH durante 1 ms
        // --------------------------------------------------------

        #1_000_000;


        // --------------------------------------------------------
        // START BIT
        //
        // RX baja durante 1/9600 s
        // --------------------------------------------------------

        RX = 1'b0;

        #104_166.667;


        // --------------------------------------------------------
        // DATA = 11000101
        //
        // Se transmite LSB first:
        //
        // bit 0 -> 1
        // bit 1 -> 0
        // bit 2 -> 1
        // bit 3 -> 0
        // bit 4 -> 0
        // bit 5 -> 0
        // bit 6 -> 1
        // bit 7 -> 1
        // --------------------------------------------------------

        RX = 1'b0;
        #104_166.667;

        RX = 1'b0;
        #104_166.667;

        RX = 1'b1;
        #104_166.667;

        RX = 1'b0;
        #104_166.667;

        RX = 1'b0;
        #104_166.667;

        RX = 1'b0;
        #104_166.667;

        RX = 1'b1;
        #104_166.667;

        RX = 1'b0;
        #104_166.667;


        // --------------------------------------------------------
        // STOP BIT
        // --------------------------------------------------------

        RX = 1'b1;

        #104_166.667;


        // --------------------------------------------------------
        // Mantener RX en HIGH
        // --------------------------------------------------------

        RX = 1'b1;

        #500_000;

        $finish;

    end

endmodule