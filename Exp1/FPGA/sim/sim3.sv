`timescale 1ns / 1ps

module tb_top;

    // ============================================================
    // Señales del TOP
    // ============================================================

    logic clk;
    logic reset;
    logic RX;
    logic boton;

    logic [6:0] segments;
    logic [3:0] enables;
    logic       punto;


    // ============================================================
    // Instancia del TOP
    // ============================================================

    Big_Boss DUT (
        .clk      (clk),
        .reset    (reset),
        .RX       (RX),
        .punto    (punto),
        .boton    (boton),
        .segments (segments),
        .enables  (enables)
    );


    // ============================================================
    // Clock de 100 MHz
    //
    // Periodo = 10 ns
    // Medio periodo = 5 ns
    // ============================================================

    initial begin
        clk = 1'b0;

        forever begin
            #5 clk = ~clk;
        end
    end


    // ============================================================
    // Tarea para transmitir un byte UART 8N1
    // ============================================================

    task uart_send_byte(input logic [7:0] dato);

        integer i;

        begin

            // ----------------------------------------------------
            // START BIT
            // ----------------------------------------------------

            RX = 1'b0;
            #104166.667;


            // ----------------------------------------------------
            // 8 DATA BITS
            // LSB first
            // ----------------------------------------------------

            for (i = 0; i < 8; i = i + 1) begin
                RX = dato[i];
                #104166.667;
            end


            // ----------------------------------------------------
            // STOP BIT
            // ----------------------------------------------------

            RX = 1'b1;
            #104166.667;


            // ----------------------------------------------------
            // IDLE
            // ----------------------------------------------------

            RX = 1'b1;

        end

    endtask


    // ============================================================
    // Simulación
    // ============================================================

    initial begin

        // --------------------------------------------------------
        // Estado inicial
        // --------------------------------------------------------

        RX    = 1'b1;
        reset = 1'b1;
        boton = 1'b0;
        DUT.L1.state = 2'b00;


        // --------------------------------------------------------
        // Reset
        // --------------------------------------------------------

        #500_000;

        reset = 1'b0;

        #500_000;
        
        RX = 1'b0;
        
        #5_000_000;
        
        RX = 1'b1;
        
        #5_000_000;
        

        // --------------------------------------------------------
        // BYTE 1
        // 0x04
        // --------------------------------------------------------

        uart_send_byte(8'h06);


        // Tiempo entre bytes
        #104166.667;


        // --------------------------------------------------------
        // BYTE 2
        // 0xD2
        // --------------------------------------------------------

        uart_send_byte(8'h72);


        // --------------------------------------------------------
        // Dejar la línea en IDLE
        // --------------------------------------------------------

        RX = 1'b1;

        #1_000_000;


        // --------------------------------------------------------
        // Fin de simulación
        // --------------------------------------------------------
      ;

    end

endmodule